"""Genera src/Presentation/IngenIA365ERP.Shared/Services/Security/MapaDelMenu.g.cs.

2026-11-19 (pedido del dueño): la pantalla de Roles dice, para cada permiso, en qué opción del menú se usa y de qué
módulo es. Esa relación no vive en la base: está en el marcado. El menú (Layout/NavMenu.razor) dice qué opciones hay,
en qué módulo y subgrupo, y qué permiso las muestra; cada pantalla (@page) dice con <PermissionGate> qué permiso la
abre (MostrarAviso="true") y cuáles habilitan sus botones. Este guion lee las dos cosas y escribe el mapa como código.

Se corre a mano cada vez que cambia el menú o los permisos de una pantalla:

    python tools/scripts/generar-mapa-del-menu.py

La prueba de arquitectura ElMapaDelMenuEstaAlDia falla si el menú tiene una opción que el mapa no conoce.
"""
import glob
import os
import re
import sys

RAIZ = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SHARED = os.path.join(RAIZ, "src", "Presentation", "IngenIA365ERP.Shared")
MENU = os.path.join(SHARED, "Layout", "NavMenu.razor")
SALIDA = os.path.join(SHARED, "Services", "Security", "MapaDelMenu.g.cs")

TOKEN = re.compile(
    r'<NavMenuGroup\b[^>]*\bTitle="(?P<grupo>[^"]+)"'
    r'|(?P<fingrupo></NavMenuGroup>)'
    r'|<span class="nav-subgroup-title">(?P<subgrupo>[^<]+)</span>'
    r'|<PermissionGate\b(?P<gate>[^>]*)>'
    r'|(?P<fingate></PermissionGate>)'
    r'|<NavLink\s+href="(?P<href>[^"]+)"[^>]*\bclass="(?P<clase>nav-subitem|nav-item)"[^>]*>(?P<cuerpo>.*?)</NavLink>',
    re.S,
)


def permisos_de(atributos: str) -> list[str]:
    codigos = []
    m = re.search(r'\bRequired="([^"@]+)"', atributos)
    if m:
        codigos.append(m.group(1).strip())
    m = re.search(r'\bAnyOf="@\(new\[\]\s*\{([^}]*)\}', atributos)
    if m:
        codigos += re.findall(r'"([^"]+)"', m.group(1))
    return codigos


def texto(cuerpo: str) -> str:
    m = re.search(r"<span>([^<]+)</span>", cuerpo)
    if m:
        return m.group(1).strip()
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>|@\w+", "", cuerpo)).strip()


def leer_menu():
    s = open(MENU, encoding="utf-8").read()
    s = re.sub(r"@\*.*?\*@", "", s, flags=re.S)
    grupo, subgrupo, pila, opciones = None, None, [], []
    for m in TOKEN.finditer(s):
        if m.group("grupo"):
            grupo, subgrupo = m.group("grupo"), None
        elif m.group("fingrupo"):
            grupo, subgrupo = None, None
        elif m.group("subgrupo"):
            subgrupo = m.group("subgrupo").strip()
        elif m.group("gate") is not None:
            pila.append(permisos_de(m.group("gate")))
        elif m.group("fingate"):
            if pila:
                pila.pop()
        elif m.group("href"):
            nombre = texto(m.group("cuerpo"))
            if not nombre:
                continue
            gates = list(dict.fromkeys(c for nivel in pila for c in nivel))
            opciones.append((grupo or "Sistema", subgrupo, nombre, m.group("href"), gates))
    return opciones


def leer_pantallas():
    pantallas = {}
    for p in glob.glob(os.path.join(SHARED, "Pages", "**", "*.razor"), recursive=True):
        s = open(p, encoding="utf-8").read()
        rutas = re.findall(r'@page\s+"([^"]+)"', s)
        if not rutas:
            continue
        acceso, acciones = [], []
        for g in re.finditer(r"<PermissionGate\b([^>]*)>", s):
            destino = acceso if 'MostrarAviso="true"' in g.group(1) else acciones
            for c in permisos_de(g.group(1)):
                if c not in destino:
                    destino.append(c)
        acciones = [c for c in acciones if c not in acceso]
        for r in rutas:
            pantallas[r.lower()] = (acceso, acciones)
    return pantallas


def cs(valor):
    if valor is None:
        return "null"
    return '"' + valor.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lista(codigos):
    return "[" + ", ".join(cs(c) for c in codigos) + "]"


def main():
    opciones = leer_menu()
    pantallas = leer_pantallas()
    lineas = []
    vistas = set()
    for grupo, subgrupo, nombre, href, gates in opciones:
        clave = (grupo, href)
        if clave in vistas:
            continue
        vistas.add(clave)
        ruta = href.split("?")[0].lower()
        acceso, acciones = pantallas.get(ruta, ([], []))
        lineas.append(
            f"        new({cs(grupo)}, {cs(subgrupo)}, {cs(nombre)}, {cs(href)}, {lista(gates)}, {lista(acceso)}, {lista(acciones)}),"
        )
    cuerpo = "\n".join(lineas)
    contenido = f"""// <auto-generated>
// Generado por tools/scripts/generar-mapa-del-menu.py a partir de Layout/NavMenu.razor y de los <PermissionGate> de
// cada pantalla. No se edita a mano: se vuelve a correr el guion.
// </auto-generated>
#nullable enable

namespace IngenIA365ERP.Shared.Services.Security;

public static partial class MapaDelMenu
{{
    /// <summary>Las opciones del menú, en el orden en que aparecen.</summary>
    public static readonly IReadOnlyList<Opcion> Opciones =
    [
{cuerpo}
    ];
}}
"""
    with open(SALIDA, "w", encoding="utf-8", newline="\n") as f:
        f.write(contenido)
    print(f"{len(lineas)} opciones -> {os.path.relpath(SALIDA, RAIZ)}")


if __name__ == "__main__":
    sys.exit(main())
